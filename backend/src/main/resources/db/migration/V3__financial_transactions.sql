CREATE TABLE financial_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type VARCHAR(20) NOT NULL,
    document_type VARCHAR(10),
    tenant_name VARCHAR(160) NOT NULL,
    document_number VARCHAR(20) NOT NULL,
    property_registration VARCHAR(80) NOT NULL,
    transaction_date DATE NOT NULL,
    gross_amount DECIMAL(19, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_financial_transaction_date
    ON financial_transaction (transaction_date);

CREATE INDEX idx_financial_transaction_type_date
    ON financial_transaction (transaction_type, transaction_date);
